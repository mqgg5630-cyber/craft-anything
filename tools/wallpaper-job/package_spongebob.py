STYLE = ['flat-2d'] * 4 + ['clay-3d'] * 6


def cjk_font_path():
    """Locate a CJK face from the installed mplfonts package, else fall back to DejaVu."""
    spec = importlib.util.find_spec('mplfonts')
    if spec and spec.origin:
        for name in ('NotoSansCJKsc-Regular.otf', 'SimHei.ttf'):
            candidate = Path(spec.origin).parent / 'fonts' / name
            if candidate.is_file():
                return candidate
    return LATIN


SANS = cjk_font_path()


def font(size, path=None):
    return ImageFont.truetype(str(path or LATIN), size)


def normalise(raw_path, out_path):
    """Crop to the target ratio (bottom-anchored so the artwork band survives), then resample."""
    with Image.open(raw_path) as im:
        image = im.convert('RGB')
    w, h = image.size
    ratio = TARGET[0] / TARGET[1]
    if w / h > ratio:                      # too wide -> crop width, centred
        new_w = round(h * ratio)
        box = (round((w - new_w) / 2), 0, round((w - new_w) / 2) + new_w, h)
    else:                                   # too tall -> crop the empty sky at the top
        new_h = round(w / ratio)
        box = (0, h - new_h, w, h)
    image.crop(box).resize(TARGET, Image.LANCZOS).save(out_path, optimize=True)
    return list(image.size)


def _top_luminance(image):
    """Mean brightness of the clock band, so the overlay text picks a readable colour."""
    w, h = image.size
    band = image.convert('L').crop((0, 0, w, round(h * 0.24))).resize((32, 24), Image.BOX)
    return sum(band.getdata()) / (32 * 24)


def adaptive_ink(image):
    """Dark ink over a pale clock band, light ink over a dark one."""
    return (58, 52, 48, 235) if _top_luminance(image) > 140 else (255, 252, 246, 235)


def lock_overlay(image):
    """Illustrative lock screen: date above a thin clock, plus the usual shortcuts."""
    image = image.convert('RGBA')
    w, h = image.size
    light_bg = _top_luminance(image) > 140
    ink = adaptive_ink(image)
    layer = Image.new('RGBA', image.size)
    d = ImageDraw.Draw(layer)
    d.text((w / 2, h * .088), '11月20日 星期四', font=font(round(w * .034), SANS), fill=ink, anchor='mt')
    d.text((w / 2, h * .112), '09:41', font=font(round(w * .155)), fill=ink, anchor='mt')
    d.text((w * .5, h * .028), '09:41', font=font(round(w * .026)), fill=ink, anchor='mt')
    bx, by = round(w * .74), round(h * .028)
    for i in range(4):
        d.rounded_rectangle((bx + i * 6, by + 10 - i * 3, bx + i * 6 + 4, by + 13), radius=1, fill=ink)
    d.rounded_rectangle((bx + 30, by, bx + 60, by + 14), radius=4, outline=ink, width=2)
    d.rounded_rectangle((bx + 33, by + 3, bx + 54, by + 11), radius=2, fill=ink)
    for x, kind in ((w * .14, 'light'), (w * .86, 'camera')):
        cy, r = h * .915, w * .052
        fill = (28, 26, 24, 120) if light_bg else (255, 255, 255, 120)
        d.ellipse((x - r, cy - r, x + r, cy + r), fill=fill, outline=ink, width=2)
        if kind == 'camera':
            d.rounded_rectangle((x - w * .022, cy - w * .014, x + w * .022, cy + w * .016),
                                radius=round(w * .007), outline=ink, width=3)
            d.ellipse((x - w * .009, cy - w * .007, x + w * .009, cy + w * .011), outline=ink, width=3)
        else:
            d.polygon([(x - w * .016, cy - w * .019), (x + w * .016, cy - w * .019),
                       (x + w * .010, cy - w * .004), (x + w * .008, cy + w * .019),
                       (x - w * .008, cy + w * .019), (x - w * .010, cy - w * .004)], fill=ink)
    d.rounded_rectangle((w * .35, h * .972, w * .65, h * .978), radius=3, fill=ink)
    return Image.alpha_composite(image, layer).convert('RGB')


ICONS = ['相机', '照片', '音乐', '天气', '时钟', '地图', '备忘录', '设置',
         '日历', '邮件', '钱包', '健康', '播客', '文件', '商店', '相册']


def home_overlay(image):
    """Illustrative home screen: blurred wallpaper, frosted card, 4x4 grid, dock."""
    src = image.convert('RGB')
    w, h = src.size
    base = src.resize((max(1, w // 6), max(1, h // 6)), Image.LANCZOS)
    base = base.filter(ImageFilter.GaussianBlur(6)).resize((w, h), Image.LANCZOS)
    base = Image.blend(base, Image.new('RGB', (w, h), (96, 90, 86)), .12)
    layer = Image.new('RGBA', (w, h))
    d = ImageDraw.Draw(layer)
    light_bg = _top_luminance(base) > 150
    text = (60, 54, 50, 245) if light_bg else (255, 253, 250, 240)
    warm = (232, 148, 74, 220) if light_bg else (255, 190, 120, 220)
    d.text((w * .5, h * .030), '09:41', font=font(round(w * .028)), fill=text, anchor='mt')
    card = (round(w * .055), round(h * .075), round(w * .945), round(h * .965))
    veil = (252, 250, 248, 96) if light_bg else (240, 238, 236, 58)
    d.rounded_rectangle(card, radius=round(w * .075), fill=veil)
    cols, rows = 4, 4
    left, right = w * .115, w * .885
    top = h * .135
    step_x = (right - left) / (cols - 1)
    step_y = h * .165
    for i, name in enumerate(ICONS[:cols * rows]):
        cx = left + (i % cols) * step_x
        cy = top + (i // cols) * step_y
        rad = w * .058
        d.rounded_rectangle((cx - rad, cy - rad, cx + rad, cy + rad), radius=round(w * .026),
                            fill=(255, 255, 255, 130) if light_bg else (252, 250, 248, 46),
                            outline=(255, 255, 255, 140), width=2)
        k = i % 4
        if k == 0:
            d.ellipse((cx - rad * .42, cy - rad * .42, cx + rad * .42, cy + rad * .42), outline=warm, width=3)
            d.ellipse((cx - rad * .16, cy - rad * .16, cx + rad * .16, cy + rad * .16), fill=warm)
        elif k == 1:
            d.line((cx, cy - rad * .55, cx + rad * .55, cy + rad * .30), fill=warm, width=4)
            d.line((cx, cy + rad * .55, cx + rad * .55, cy + rad * .30), fill=warm, width=4)
        elif k == 2:
            for j in range(3):
                d.line((cx - rad * .5, cy - rad * .3 + j * rad * .30, cx + rad * .5, cy - rad * .3 + j * rad * .30),
                       fill=warm, width=3)
        else:
            d.arc((cx - rad * .55, cy - rad * .55, cx + rad * .55, cy + rad * .55), 0, 300, fill=warm, width=4)
        d.text((cx, cy + rad + h * .012), name, font=font(round(w * .021), SANS), fill=text, anchor='mt')
    dock_top = h * .845
    d.rounded_rectangle((round(w * .115), round(dock_top), round(w * .885), round(h * .945)),
                        radius=round(w * .085), fill=veil)
    for i in range(4):
        cx = w * .19 + i * w * .207
        cy = dock_top + h * .04
        rad = w * .056
        d.ellipse((cx - rad, cy - rad, cx + rad, cy + rad), fill=(255, 255, 255, 140))
    d.rounded_rectangle((w * .35, h * .972, w * .65, h * .978), radius=3, fill=(255, 255, 255, 220))
    return Image.alpha_composite(base.convert('RGBA'), layer).convert('RGB')


def phone(image, width):
    """Draw one device mock-up around a wallpaper (used only for the cover)."""
    scale = width / image.size[0]
    body = image.resize((width, round(image.size[1] * scale)), Image.LANCZOS)
    radius = round(width * .12)
    mask = Image.new('L', body.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, body.size[0], body.size[1]), radius=radius, fill=255)
    frame_w = max(4, round(width * .022))
    canvas = Image.new('RGB', (body.size[0] + frame_w * 2, body.size[1] + frame_w * 2), (44, 40, 38))
    canvas.paste(body, (frame_w, frame_w), mask)
    return canvas


def record(path):
    data = path.read_bytes()
    with Image.open(path) as im:
        im.verify()
    with Image.open(path) as im:
        size = list(im.size)
    return {'file': str(path.relative_to(ROOT)), 'width': size[0], 'height': size[1],
            'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def sheet(files, target, label, thumb=(210, 400), cols=5):
    if not files:
        return
    rows = (len(files) + cols - 1) // cols
    cell_w, cell_h = thumb[0] + 20, thumb[1] + 46
    result = Image.new('RGB', (cols * cell_w + 20, rows * cell_h + 60), '#f2f0ee')
    d = ImageDraw.Draw(result)
    d.text((20, 18), label, font=font(26, SANS), fill='#4a443e')
    for i, path in enumerate(files):
        x, y = 20 + (i % cols) * cell_w, 60 + (i // cols) * cell_h
        with Image.open(path) as im:
            piece = ImageOps.contain(im.convert('RGB'), thumb, Image.LANCZOS)
        d.text((x, y), path.name[:2], font=font(18), fill='#5a544e')
        result.paste(piece, (x, y + 24))
    result.save(target, quality=92)


def cover(clean, locks, target_clean, target_lock):
    """Xiaohongshu cover: soft blurred band of the art behind two centred phone mock-ups."""
    width, height = 1080, 1440
    for pair, dest in (([clean[2], locks[2]], target_clean), ([locks[0], locks[4]], target_lock)):
        with Image.open(clean[0]) as im:
            band = ImageOps.fit(im.convert('RGB'), (width, height), Image.LANCZOS, centering=(.5, .3))
        band = band.filter(ImageFilter.GaussianBlur(26))
        canvas = Image.blend(band, Image.new('RGB', (width, height), (246, 236, 224)), .82)
        d = ImageDraw.Draw(canvas)
        d.text((540, 96), '海绵宝宝 & 派大星 · 四季治愈壁纸', font=font(40, SANS), fill='#6b5b4d', anchor='mm')
        d.text((540, 158), '十张 · 扁平卡通 + 粘土微缩 · 锁屏 / 桌面都配好', font=font(26, SANS),
               fill='#8a7767', anchor='mm')
        pieces = [phone(Image.open(p).convert('RGB'), 420) for p in pair]
        total_w = sum(p.size[0] for p in pieces) + 60
        tallest = max(p.size[1] for p in pieces)
        top = 210 + round((height - 210 - 70 - tallest) / 2)
        x = (width - total_w) // 2
        for piece in pieces:
            shadow = Image.new('RGBA', (piece.size[0] + 40, piece.size[1] + 40), (0, 0, 0, 0))
            ImageDraw.Draw(shadow).ellipse((20, piece.size[1], piece.size[0] + 20, piece.size[1] + 36),
                                           fill=(90, 70, 50, 70))
            shadow = shadow.filter(ImageFilter.GaussianBlur(8))
            canvas.paste(shadow, (x - 20, top - 20), shadow)
            canvas.paste(piece, (x, top))
            x += piece.size[0] + 60
        d.text((540, height - 40), '风格参考原帖 1 / 3 / 5 · AI 复刻 · 自用非商业',
               font=font(22, SANS), fill='#9a8878', anchor='mm')
        canvas.save(dest, quality=92)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raw', type=Path, default=Path('/tmp/sbraw'),
                        help='folder holding the ten model-native gen_NN.png outputs')
    parser.add_argument('--skip-normalise', action='store_true',
                        help='only re-render previews, sheets and the manifest')
    args = parser.parse_args()

    log = json.loads((SOURCES / '下载记录.json').read_text(encoding='utf-8'))
    for entry in log['images']:
        path = SOURCES / entry['file']
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry['sha256']:
            raise SystemExit('Source hash mismatch: downloaded originals changed')

    native = {}
    if not args.skip_normalise:
        CLEAN.mkdir(parents=True, exist_ok=True)
        for i, stem in enumerate(NAMES, 1):
            raw = args.raw / f'gen_{i:02d}.png'
            if not raw.is_file():
                raise SystemExit(f'missing model output {raw}')
            native[stem] = normalise(raw, CLEAN / f'{stem}.png')

    clean = sorted(CLEAN.glob('*.png'))
    if len(clean) != 10:
        raise SystemExit(f'expected 10 clean wallpapers, found {len(clean)}')
    if any(Image.open(p).size != TARGET for p in clean):
        raise SystemExit('a clean wallpaper is not 1080x1920')

    LOCK.mkdir(exist_ok=True)
    HOME.mkdir(exist_ok=True)
    REPORT.mkdir(exist_ok=True)
    before = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in clean}
    for path in clean:
        stem = path.stem
        with Image.open(path) as im:
            lock_overlay(im).save(LOCK / f'{stem}-锁屏.jpg', quality=92, optimize=True)
        with Image.open(path) as im:
            home_overlay(im).save(HOME / f'{stem}-桌面.jpg', quality=92, optimize=True)
    after = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in clean}
    if before != after:
        raise SystemExit('Clean wallpapers were modified while rendering previews')

    locks = sorted(LOCK.glob('*.jpg'))
    homes = sorted(HOME.glob('*.jpg'))
    sources = sorted(SOURCES.glob('*.webp')) + sorted(SOURCES.glob('*.png'))
    sources = sorted(sources, key=lambda p: p.name)
    sheet(sources, REPORT / '下载原图总览.jpg', '参考原图 · 原帖公开 6 张（公开 CDN 原字节）',
          thumb=(300, 400), cols=3)
    sheet(clean, REPORT / '无UI总览.jpg', '复刻壁纸 · 10 张（无手机 UI）')
    sheet(locks, REPORT / '锁屏预览总览.jpg', f'锁屏预览 · {len(locks)} 张（示意叠层，非真机截图）')
    sheet(homes, REPORT / '桌面预览总览.jpg', f'桌面预览 · {len(homes)} 张（示意叠层，非真机截图）')
    cover(clean, locks, REPORT / '封面-双机预览-无UI.jpg', REPORT / '封面-双机预览-锁屏.jpg')

    manifest = {
        'schema_version': 1,
        'status': 'complete',
        'note_id': log['note_id'],
        'title': log['title'],
        'author': log['author'],
        'share_url': log['share_url'],
        'replica_count': len(clean),
        'style_anchor': ('复刻风格取自原帖 1 / 3 / 5 三张：1 号为扁平二维卡通 + 顶部整片纯色留白，'
                         '3 号与 5 号为粘土微缩 + 大面积天空留白。2 / 4 / 6 号油画质感仅作参考，未模仿。'),
        'generation': {
            'model_native_size': '768x1376',
            'final_size': '1080x1920',
            'method': 'crop to 1080:1920 (top-anchored crop of the empty sky), then Lanczos resample; never stretched',
            'reference_images': ['01-下载原图/01.webp (扁平卡通 4 张)',
                                 '01-下载原图/03.webp + 05.webp (粘土 6 张)'],
            'per_file_native_size': native or 'see previous run recorded in 02 file sizes',
        },
        'clean_ui_policy': '03/04 previews are separate files; 02 clean wallpapers are never overwritten.',
        'ui': 'Deterministic illustrative lock and home previews; not device screenshots.',
        'sources': [record(p) for p in sources],
        'clean': [dict(record(p), style=STYLE[i]) for i, p in enumerate(clean)],
        'lock_previews': [record(p) for p in locks],
        'home_previews': [record(p) for p in homes],
        'sheets': [record(p) for p in sorted(REPORT.glob('*.jpg'))],
    }
    (REPORT / '验收记录.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n',
                                          encoding='utf-8')
    print(f'{len(sources)} sources, {len(clean)} clean, {len(locks)} lock, {len(homes)} home, '
          f'{len(manifest["sheets"])} sheets')


if __name__ == '__main__':
    sys.exit(main())
