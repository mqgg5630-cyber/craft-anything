"""Normalise, preview and verify the 「海绵宝宝 & 派大星四季治愈壁纸」 replica delivery.

The ten wallpapers are AI generated by the conversation's image tool; this script only
does the deterministic post-processing that follows: crop the model-native output to the
note's own 1080:1920 ratio (crop + Lanczos resample, never a stretch), render illustrative
lock-screen and home-screen previews onto *copies*, build the contact sheets and the cover,
and write `验收记录.json`. It never draws on a clean wallpaper.

Run:  .venv/bin/python tools/wallpaper-job/package_spongebob.py --raw /tmp/sbraw
"""
