from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps

ROOT = Path('deliveries/spongebob-patrick-5ciq9ne8i38')
SOURCES = ROOT / '01-下载原图'
CLEAN = ROOT / '02-复刻无手机UI'
LOCK = ROOT / '03-锁屏预览'
HOME = ROOT / '04-桌面预览'
REPORT = ROOT / '05-说明与验收'

TARGET = (1080, 1920)          # the note's own canvas is 1080x1922
LATIN = Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')

